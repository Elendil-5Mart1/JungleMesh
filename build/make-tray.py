# Generates the notification-area icons (spider web without background, simplified to stay readable at 16 px)
# → src/main/trayImages.ts (PNG as base64: no image file to ship with the app)
# Two colors (2026-11-24): white web on a dark taskbar, black web on a light one (chosen by src/main/icons.ts)
import base64, io, math, os, tempfile
from PIL import Image, ImageDraw

S = 1024  # reference grid
C = S / 2
SPOKES = 8
RINGS = [0.36, 0.66, 0.96]
R = S / 2 * 0.94
SAG = 0.14
WHITE, BLACK, RED = (255, 255, 255), (20, 22, 26), (237, 66, 69)
CLEAR = (0, 0, 0, 0)
rot = -math.pi / 2 + math.pi / SPOKES

def pt(r, i):
    a = rot + i * 2 * math.pi / SPOKES
    return (C + r * math.cos(a), C + r * math.sin(a))

def quad(p0, c, p1, n=20):
    return [((1-t)**2*p0[0]+2*(1-t)*t*c[0]+t*t*p1[0], (1-t)**2*p0[1]+2*(1-t)*t*c[1]+t*t*p1[1]) for t in (k/n for k in range(n+1))]

def render(web, unread):
    k = 2
    img = Image.new('RGBA', (S*k, S*k), CLEAR)
    d = ImageDraw.Draw(img)
    for i in range(SPOKES):
        a, b = pt(R * 0.06, i), pt(R, i)
        d.line([(a[0]*k, a[1]*k), (b[0]*k, b[1]*k)], fill=web, width=70*k)
    for rr in RINGS:
        r = R * rr
        for i in range(SPOKES):
            p0, p1 = pt(r, i), pt(r, i + 1)
            mid = pt(r * (1 - SAG * (1 - rr * 0.5)), i + 0.5)
            ctrl = (2*mid[0]-(p0[0]+p1[0])/2, 2*mid[1]-(p0[1]+p1[1])/2)
            d.line([(x*k, y*k) for x, y in quad(p0, ctrl, p1)], fill=web, width=64*k, joint='curve')
    if unread:  # transparent ring (cut into the web, readable on any taskbar) then red dot, bottom right
        for rad, col in ((300, CLEAR), (230, RED)):
            cx = cy = 760
            d.ellipse([(cx-rad)*k, (cy-rad)*k, (cx+rad)*k, (cy+rad)*k], fill=col)
    return img.resize((32, 32), Image.LANCZOS)

def b64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True)
    return base64.b64encode(buf.getvalue()).decode()

icons = {f'{name}{suffix}': render(col, unread)
         for name, col in (('TRAY_WHITE', WHITE), ('TRAY_BLACK', BLACK))
         for suffix, unread in (('_PNG', False), ('_UNREAD_PNG', True))}
open('src/main/trayImages.ts', 'w', encoding='utf-8', newline='\n').write(
    '//* Notification-area icons (generated by build/make-tray.py, do not edit by hand)\n'
    '// 32 px PNG, shown at 16 px (scaleFactor 2). WHITE for a dark taskbar, BLACK for a light one\n'
    + ''.join(f"export const {name} = '{b64(img)}'\n" for name, img in icons.items()))
# enlarged previews to check by eye: white icons on a dark band, black icons on a light band
sheet = Image.new('RGBA', (512, 512), (32, 36, 44, 255))
sheet.paste((238, 240, 244, 255), (0, 256, 512, 512))
for n, (name, img) in enumerate(icons.items()):
    big = img.resize((256, 256), Image.NEAREST)
    sheet.paste(big, ((n % 2) * 256, (n // 2) * 256), big)
sheet.save(os.path.join(tempfile.gettempdir(), 'junglemesh-tray-preview.png'))  # %TEMP%
print('ok')
