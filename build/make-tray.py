# Generates the notification-area icons (spider web without background, simplified to stay readable at 16 px)
# → src/main/trayImages.ts (PNG as base64: no image file to ship with the app)
import base64, io, math
from PIL import Image, ImageDraw

S = 1024  # reference grid
C = S / 2
SPOKES = 8
RINGS = [0.36, 0.66, 0.96]
R = S / 2 * 0.94
SAG = 0.14
TEAL, RED, DARK = (31, 209, 200), (237, 66, 69), (13, 17, 20)
rot = -math.pi / 2 + math.pi / SPOKES

def pt(r, i):
    a = rot + i * 2 * math.pi / SPOKES
    return (C + r * math.cos(a), C + r * math.sin(a))

def quad(p0, c, p1, n=20):
    return [((1-t)**2*p0[0]+2*(1-t)*t*c[0]+t*t*p1[0], (1-t)**2*p0[1]+2*(1-t)*t*c[1]+t*t*p1[1]) for t in (k/n for k in range(n+1))]

def render(unread):
    k = 2
    img = Image.new('RGBA', (S*k, S*k), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for i in range(SPOKES):
        a, b = pt(R * 0.06, i), pt(R, i)
        d.line([(a[0]*k, a[1]*k), (b[0]*k, b[1]*k)], fill=TEAL, width=70*k)
    for rr in RINGS:
        r = R * rr
        for i in range(SPOKES):
            p0, p1 = pt(r, i), pt(r, i + 1)
            mid = pt(r * (1 - SAG * (1 - rr * 0.5)), i + 0.5)
            ctrl = (2*mid[0]-(p0[0]+p1[0])/2, 2*mid[1]-(p0[1]+p1[1])/2)
            d.line([(x*k, y*k) for x, y in quad(p0, ctrl, p1)], fill=TEAL, width=64*k, joint='curve')
    if unread:  # dark outline then red dot, bottom right
        for rad, col in ((300, DARK), (230, RED)):
            cx = cy = 760
            d.ellipse([(cx-rad)*k, (cy-rad)*k, (cx+rad)*k, (cy+rad)*k], fill=col)
    return img.resize((32, 32), Image.LANCZOS)

def b64(img):
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True)
    return base64.b64encode(buf.getvalue()).decode()

plain, dot = render(False), render(True)
open('src/main/trayImages.ts', 'w', encoding='utf-8').write(
    '//* Notification-area icons (generated by build/make-tray.py, do not edit by hand)\n'
    '// 32 px PNG, shown at 16 px (scaleFactor 2)\n'
    f"export const TRAY_PNG = '{b64(plain)}'\n"
    f"export const TRAY_UNREAD_PNG = '{b64(dot)}'\n")
# enlarged previews to check by eye
sheet = Image.new('RGBA', (32*8*2, 32*8), (40, 44, 52, 255))
sheet.paste(plain.resize((256, 256), Image.NEAREST), (0, 0), plain.resize((256, 256), Image.NEAREST))
sheet.paste(dot.resize((256, 256), Image.NEAREST), (256, 0), dot.resize((256, 256), Image.NEAREST))
