//* Config plugin: the app's data never leaves the phone through Android's backups
// The private folder holds the Corestore master key, i.e. the IDENTITY: a copy elsewhere is a stolen account.
// - `allowBackup: false` (app.json) stops the Google Drive backup… but since Android 12 it no longer stops
//   the device-to-device transfer (new phone set up from the old one, cable or Wi-Fi).
// - Hence dataExtractionRules: everything excluded, for the cloud backup AND the device transfer.
//   A transfer would also be dangerous for the logs: two phones writing the same Hypercore with the
//   same key = a fork, which the friends' copies reject. Moving to a new phone = identity backup (later).
const fs = require('fs')
const path = require('path')
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins')

const RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNoBackup.js: nothing is backed up or transferred (see the plugin) -->
<data-extraction-rules>
  <cloud-backup>
    <exclude domain="root" path="." />
    <exclude domain="file" path="." />
    <exclude domain="database" path="." />
    <exclude domain="sharedpref" path="." />
    <exclude domain="external" path="." />
  </cloud-backup>
  <device-transfer>
    <exclude domain="root" path="." />
    <exclude domain="file" path="." />
    <exclude domain="database" path="." />
    <exclude domain="sharedpref" path="." />
    <exclude domain="external" path="." />
  </device-transfer>
</data-extraction-rules>
`

const withRulesFile = (config) =>
  withDangerousMod(config, [
    'android',
    (mod) => {
      const dir = path.join(mod.modRequest.platformProjectRoot, 'app/src/main/res/xml')
      fs.mkdirSync(dir, { recursive: true })
      fs.writeFileSync(path.join(dir, 'data_extraction_rules.xml'), RULES)
      return mod
    }
  ])

const withRulesAttribute = (config) =>
  withAndroidManifest(config, (mod) => {
    const app = mod.modResults.manifest.application[0]
    app.$['android:allowBackup'] = 'false'
    app.$['android:dataExtractionRules'] = '@xml/data_extraction_rules'
    return mod
  })

module.exports = function withNoBackup(config) {
  return withRulesAttribute(withRulesFile(config))
}
