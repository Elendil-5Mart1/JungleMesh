//* Icons built in code (no image files to ship): the taskbar badge is drawn, the tray icon is embedded
// Format expected by nativeImage.createFromBitmap: BGRA, colors premultiplied by alpha.
import { nativeImage, nativeTheme, type NativeImage } from 'electron'
import { TRAY_BLACK_PNG, TRAY_BLACK_UNREAD_PNG, TRAY_WHITE_PNG, TRAY_WHITE_UNREAD_PNG } from './trayImages'

interface Disc {
  cx: number // center and radius, as a fraction of the size (0 → 1)
  cy: number
  r: number
  color: [number, number, number] // RGB
}

// Draws stacked discs (the last one on top), with soft edges
const paint = (discs: Disc[], px: number, scale: number): NativeImage => {
  const buf = Buffer.alloc(px * px * 4)
  for (let y = 0; y < px; y++) {
    for (let x = 0; x < px; x++) {
      let [r, g, b, a] = [0, 0, 0, 0]
      for (const d of discs) {
        const dist = Math.hypot(x + 0.5 - d.cx * px, y + 0.5 - d.cy * px)
        const cover = Math.max(0, Math.min(1, d.r * px - dist + 0.5)) // anti-aliasing
        // "over" operator: the disc covers what is below according to its coverage
        r = d.color[0] * cover + r * (1 - cover)
        g = d.color[1] * cover + g * (1 - cover)
        b = d.color[2] * cover + b * (1 - cover)
        a = cover + a * (1 - cover)
      }
      const i = (y * px + x) * 4
      buf[i] = b * a
      buf[i + 1] = g * a
      buf[i + 2] = r * a
      buf[i + 3] = 255 * a
    }
  }
  return nativeImage.createFromBitmap(buf, { width: px, height: px, scaleFactor: scale })
}

const DANGER: [number, number, number] = [0xed, 0x42, 0x45] // $danger

// Unread badge placed on the taskbar buttons
export const unreadDot = (): NativeImage => paint([{ cx: 0.5, cy: 0.5, r: 0.44, color: DANGER }], 16, 1)

// Is the taskbar / menu bar dark? On Windows it has its own theme ("Choose your default Windows mode"),
// separate from the apps' theme: shouldUseDarkColorsForSystemIntegratedUI reads that one. On macOS it is
// the same as shouldUseDarkColors. Linux has no such setting: the GTK theme is the best guess.
export const darkTaskbar = (): boolean =>
  process.platform === 'linux' ? nativeTheme.shouldUseDarkColors : nativeTheme.shouldUseDarkColorsForSystemIntegratedUI

const TRAY_PNGS = {
  white: TRAY_WHITE_PNG,
  whiteUnread: TRAY_WHITE_UNREAD_PNG,
  black: TRAY_BLACK_PNG,
  blackUnread: TRAY_BLACK_UNREAD_PNG
}

// Notification-area icon: the spider-web logo, white on a dark taskbar and black on a light one,
// with a red dot if there are unread messages.
// 32 px PNG with scaleFactor 2 → sharp on 200 % screens (images generated by build/make-tray.py).
// Decoded once each: the tray is refreshed on every state change
const trayImages = new Map<keyof typeof TRAY_PNGS, NativeImage>()
export const trayIcon = (hasUnread: boolean, dark: boolean): NativeImage => {
  const name = `${dark ? 'white' : 'black'}${hasUnread ? 'Unread' : ''}` as keyof typeof TRAY_PNGS
  let image = trayImages.get(name)
  if (!image) {
    image = nativeImage.createFromBuffer(Buffer.from(TRAY_PNGS[name], 'base64'), { scaleFactor: 2 })
    trayImages.set(name, image)
  }
  return image
}
